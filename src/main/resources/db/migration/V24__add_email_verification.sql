-- 이메일 소유권 인증 — docs/architecture.md 인증 장 "이메일 인증", docs/api.md 비밀번호·이메일 장
--   기존 행의 값은 바꾸지 않음: users에 NULL 허용 컬럼 1개 + 새 테이블 1개
--   V23으로 등록된 이메일은 email_verified_at = NULL(미인증)로 남음 → 인증 전에는 비밀번호 찾기에 쓰이지 않음

-- 1. 이메일 인증 시각 — NULL이면 미인증 (V24 이전에 확인 없이 등록된 주소)
--    V24부터 users.email은 인증 링크를 연 순간에만 채워지므로 새로 들어가는 값은 항상 인증된 주소
--    CHECK: 주소 없이 인증 시각만 있는 행이 생기지 않도록
ALTER TABLE users ADD COLUMN email_verified_at timestamp(6);
ALTER TABLE users ADD CONSTRAINT users_email_verified_check
    CHECK (email_verified_at IS NULL OR email IS NOT NULL);

-- 2. 이메일 인증 토큰 — 인증 메일 링크 1개 = 행 1개 (password_reset_tokens와 같은 구조 + 인증할 주소)
--    email      : 인증이 끝나면 users.email이 될 주소 (정규화된 소문자). 인증 전에는 UNIQUE를 차지하지 않음
--                 → 남의 주소를 먼저 적어도 그 주소를 선점하지 못함. 여러 회원이 같은 주소로 대기해도 먼저 인증한 쪽만 성공 (uk_users_email)
--    token_hash : 원문이 아닌 SHA-256(hex) — DB가 유출돼도 저장된 값으로 인증할 수 없음
--    used_at    : 더 쓸 수 없게 된 시각 — 인증에 사용, 새 링크 발급, 변경 취소 중 하나. NULL이고 만료 전이면 사용 가능
--    행은 used_at만 한 번 바뀌고 주소·해시·만료 시각은 바뀌지 않음
CREATE TABLE email_verification_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint       NOT NULL,
    email       varchar(255) NOT NULL,
    token_hash  varchar(64)  NOT NULL,
    created_at  timestamp(6) NOT NULL,
    expires_at  timestamp(6) NOT NULL,
    used_at     timestamp(6),
    CONSTRAINT email_verification_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT uk_email_verification_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT email_verification_tokens_email_lower_check CHECK (email = lower(email)),
    CONSTRAINT email_verification_tokens_expires_at_check CHECK (expires_at > created_at)
);

-- 회원별 최근 발급 시각(재요청 간격 제한)·대기 중인 주소 조회·이전 링크 무효화용
CREATE INDEX idx_email_verification_tokens_user_created ON email_verification_tokens (user_id, created_at);
