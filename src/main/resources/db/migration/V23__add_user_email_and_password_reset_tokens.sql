-- 비밀번호 찾기(이메일 재설정 링크)·비밀번호 변경 — docs/architecture.md 인증 장, docs/api.md 비밀번호 장
--   기존 행의 값은 바꾸지 않음: users에는 NULL 허용 컬럼만 추가(기존 회원은 이메일 없음 → 내 정보에서 등록), 새 테이블 1개

-- 1. 회원 이메일 — 비밀번호 재설정 링크를 받는 주소 (로그인 아이디는 여전히 username)
--    애플리케이션이 앞뒤 공백 제거 + 소문자로 저장 → 대소문자만 다른 주소로 두 회원이 같은 메일함을 쓰지 않도록
--    UNIQUE: 한 주소 = 한 회원 (재설정 요청이 어느 회원 것인지 하나로 정해짐). PostgreSQL UNIQUE는 NULL을 여러 개 허용
ALTER TABLE users ADD COLUMN email varchar(255);
ALTER TABLE users ADD CONSTRAINT uk_users_email UNIQUE (email);
ALTER TABLE users ADD CONSTRAINT users_email_lower_check CHECK (email = lower(email));

-- 2. 비밀번호 재설정 토큰 — 링크 1개 = 행 1개
--    token_hash : 원문이 아닌 SHA-256(hex) → DB가 유출돼도 저장된 값으로 비밀번호를 바꿀 수 없음 (refresh_tokens와 같은 방식)
--    used_at    : 더 쓸 수 없게 된 시각 — 재설정에 사용됨, 새 링크 발급, 비밀번호 변경 중 하나. NULL이고 만료 전이면 사용 가능
--    행은 used_at만 한 번 바뀌고 해시·만료 시각은 바뀌지 않음
CREATE TABLE password_reset_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint       NOT NULL,
    token_hash  varchar(64)  NOT NULL,
    created_at  timestamp(6) NOT NULL,
    expires_at  timestamp(6) NOT NULL,
    used_at     timestamp(6),
    CONSTRAINT password_reset_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT uk_password_reset_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT password_reset_tokens_expires_at_check CHECK (expires_at > created_at)
);

-- 회원별 최근 발급 시각(재요청 간격 제한)·아직 쓸 수 있는 링크 무효화용
CREATE INDEX idx_password_reset_tokens_user_created ON password_reset_tokens (user_id, created_at);

-- 3. 비밀번호 변경·재설정 시 그 회원의 다른 로그인(Refresh Token 계열)을 모두 폐기 — 폐기 사유 추가
ALTER TABLE refresh_tokens DROP CONSTRAINT refresh_tokens_revoke_reason_check;
ALTER TABLE refresh_tokens ADD CONSTRAINT refresh_tokens_revoke_reason_check
    CHECK (revoke_reason IN ('ROTATED', 'LOGOUT', 'REUSE_DETECTED', 'PASSWORD_CHANGED'));

-- 회원 단위 폐기 때 아직 유효한 행만 찾는 부분 인덱스 (계열 단위는 idx_refresh_tokens_family_active)
CREATE INDEX idx_refresh_tokens_user_active ON refresh_tokens (user_id) WHERE revoked_at IS NULL;
